# core/schemas.py
from __future__ import annotations
from typing import Sequence, Optional
from pydantic import BaseModel, Field


class CulturalSignal(BaseModel):
    """Represents a localized demand signal from the Qloo Taste Graph."""
    qloo_entity_id: str
    affinity_score: float = Field(..., ge=0.0, le=1.0)
    weight: float = Field(default=1.0, gt=0.0)


class ZoneArbitrageResult(BaseModel):
    """The computed mathematical outcome of commercial viability for a single locality."""
    zone_name: str
    demand_score: float
    saturation_index: float
    arbitrage_yield: float


class AgentClaim(BaseModel):
    """A factual statement generated by the LLM that must be grounded in Qloo data."""
    claim_id: str
    qloo_entity_id: str
    cited_affinity: float
    statement: str


class ValidationVerdict(BaseModel):
    """Result of the GroundingAuditor testing LLM claims against the Qloo graph."""
    is_valid: bool
    rejected_claim_ids: tuple[str, ...]


class UnderwritingRequest(BaseModel):
    """Inbound request payload for launching the autonomous agent."""
    concept_description: str = Field(..., min_length=10)
    target_locations: Sequence[str] = Field(..., min_length=1)
    demographic_target: Optional[str] = None


class AgentStreamEvent(BaseModel):
    """Structured payload for the NDJSON Server-Sent Event stream."""
    event_type: str
    data: dict